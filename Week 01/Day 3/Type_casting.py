#// program for type casting

a = "5"
b = "2.5"
c = "10"

a_int = int(a)  #// converting string to integer
b_float = float(b)  #// converting string to float
c_str = str(c)  #// converting integer to string

print("The integer value of a is:", a_int)
print("The float value of b is:", b_float)
print("The string value of c is:", c_str)